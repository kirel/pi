const assert=require('node:assert/strict');
const {plan,verify,shape,combineResponses,PROJECT}=require('./logic');
const task=(id,content,description='')=>({id,content,description,projectId:PROJECT,sectionId:'s',parentId:null,recurring:false});
const milk=task('1','Milch','Hafer'),duplicate=task('2','Milch','ungesüßt');
const state={complete:true,projectId:PROJECT,tasks:[milk,duplicate],sections:[{id:'s',name:'Kühlregal'}]};
const request=operations=>({request_id:'test-request-123',operations});
const add={action:'add',content:'Pesto',description:'vegan',section:'Kühlregal',expected_candidates:[]};
const p=plan(request([add]),state);
assert.equal(p.commands[0].args.project_id,PROJECT);
assert.equal(p.commands[0].args.section_id,'s');
assert.deepEqual(plan(request([add]),state).commands,p.commands);
assert.throws(()=>plan(request([add]),{...state,complete:false}),/incomplete/);
assert.throws(()=>plan(request([{...add,content:'Milch'}]),state),/stale_add/);
assert.throws(()=>plan(request([{action:'move',id:'outside',expected:{id:'outside'},section:'Kühlregal'}]),state),/missing/);
assert.throws(()=>plan(request([{action:'update',id:'1',expected:{...shape(milk),description:'stale'},description:'new'}]),state),/stale/);
assert.throws(()=>plan(request([add,add]),state),/duplicate/);
const m=plan(request([{action:'merge',id:'1',expected:shape(milk),duplicates:[{id:'2',expected:shape(duplicate)}]}]),state);
assert.equal(m.commands.length,1);assert.equal(m.commands[0].type,'item_update');
assert.equal(m.entries[0].desired.description,'Hafer\nungesüßt');
assert.equal(verify(m,{},state).commands.length,0);
const saved={...state,tasks:[{...milk,description:'Hafer\nungesüßt'},duplicate]};
assert.equal(verify(m,{},saved).commands[0].type,'item_close');
assert.equal(verify(m,{}, {...saved,tasks:[saved.tasks[0]]},true).verified,true);
assert.equal(verify(m,{}, {...saved,tasks:[saved.tasks[0],{...duplicate,description:'changed'}]}).results[0].status,'conflict');
assert.equal(verify(p,{},state).results[0].status,'uncertain');
const added=task('3','Pesto','vegan');
assert.equal(verify(p,{temp_id_mapping:{[p.entries[0].temp_id]:'3'}},{...state,tasks:[...state.tasks,added]}).verified,true);
const partial=plan(request([add,{...add,content:'Brot'}]),state);
const pr=verify(partial,{temp_id_mapping:{[partial.entries[0].temp_id]:'3'},sync_status:{[partial.entries[1].uuid]:{error_code:1}}},{...state,tasks:[...state.tasks,added]});
assert.deepEqual(pr.results.map(r=>r.status),['verified','failed']);
const completed=plan(request([{action:'complete',id:'1',expected:shape(milk)}]),state);
assert.equal(verify(completed,{}, {...state,tasks:[duplicate]}).verified,true);
assert.throws(()=>plan(request([{action:'complete',id:'1',expected:shape(milk)}]),{...state,tasks:[milk,{...duplicate,parentId:'1'}]}),/complex/);
const mixed=plan(request([add,{action:'merge',id:'1',expected:shape(milk),duplicates:[{id:'2',expected:shape(duplicate)}]}]),state);
const combined=combineResponses({temp_id_mapping:{[mixed.entries[0].temp_id]:'3'}},{temp_id_mapping:{}});
assert.equal(verify(mixed,combined,{...state,tasks:[added,{...milk,description:'Hafer\nungesüßt'}]},true).verified,true);
console.log('shopping logic: all checks passed');
